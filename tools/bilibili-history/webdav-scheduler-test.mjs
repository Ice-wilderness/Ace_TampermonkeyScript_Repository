import assert from 'node:assert/strict';
import { instance, sharedStorage } from './harness.mjs';

const shared = sharedStorage();
const a = instance(shared, 'scheduler-a'), b = instance(shared, 'scheduler-b');
const config = { url: 'https://dav.example/root/', directory: 'watch', username: '', password: '',
    frequency: 'hourly', backupRetentionDays: 7 };
const root = new a.WebDavClient(config).root, now = a.context.Date.now();
shared.data.set('bvh_webdav_config', config);
let runs = 0;
a.WebDavSync.sync = async () => { runs++; return { changed: false }; };
a.StorageManager.getCloudEntries = () => { throw new Error('未到期不得读取完整历史'); };
await a.WebDavSync.saveState({ root, lastSuccess: now, lastAttempt: 0 });
await a.WebDavSync.check();
assert.equal(runs, 0);
await a.WebDavSync.saveState({ root, lastSuccess: now - 3600000 + 1, lastAttempt: 0 });
await a.WebDavSync.check();
assert.equal(runs, 0);
await a.WebDavSync.saveState({ root, lastSuccess: now - 3600000, lastAttempt: 0 });
await a.WebDavSync.check();
assert.equal(runs, 1);
await a.WebDavSync.saveState({ root, lastSuccess: 0, lastAttempt: now - 4 * 60000 });
await a.WebDavSync.check();
assert.equal(runs, 1, '失败未满 5 分钟不得自动重试');
await a.WebDavSync.saveState({ root, lastSuccess: 0, lastAttempt: now - 5 * 60000 });
await a.WebDavSync.check();
assert.equal(runs, 2);
shared.data.set('bvh_webdav_config', { ...config, frequency: 'daily' });
await a.WebDavSync.saveState({ root, lastSuccess: now - 3600000, lastAttempt: 0 });
await a.WebDavSync.check();
assert.equal(runs, 2);
await a.WebDavSync.saveState({ root, lastSuccess: now - 86400000, lastAttempt: 0 });
await a.WebDavSync.check();
assert.equal(runs, 3);
const changedRoot = new a.WebDavClient({ ...config, directory: 'another' }).root;
assert.equal((await a.WebDavSync.state(changedRoot)).lastSuccess, 0);
assert.equal(await a.WebDavSync.lease(), true);
assert.equal(await b.WebDavSync.lease(), false, '多个标签页应优先由一页运行');
shared.data.set('bvh_webdav_lease', { owner: 'closed-tab', until: now - 1 });
assert.equal(await b.WebDavSync.lease(), true, '占用过期后其他页面可接替');
await b.WebDavSync.release();
console.log('每小时／每天边界、失败间隔、目录切换与跨标签页占用通过');
